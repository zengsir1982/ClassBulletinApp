// System.Windows.Forms（托盘）也注入全局 using，以下类型有同名冲突
using MediaColor = System.Windows.Media.Color;
using HAlign = System.Windows.HorizontalAlignment;
using VAlign = System.Windows.VerticalAlignment;

namespace ClassBulletinApp;

/// <summary>
/// 升级后的一次性说明（同一版本只弹一次，由 <c>AppSettings.UpgradeNoticeShownFor</c> 控制）。
///
/// <para>为什么要专门做：r8/r9 这几次改动里有几条**会让人以为"数据丢了"的行为变化**
/// （调课记录突然只作用于某一周、周视图突然从周日开始、清除按钮不再一把清空）。
/// 不解释一次，教室机上看到的就是"课表怎么变回去了"。</para>
/// </summary>
public class UpgradeNoticeWindow : Window
{
    public UpgradeNoticeWindow(string version, IReadOnlyList<(string Title, string Detail)> items)
    {
        Title = "更新说明";
        Width = 640;
        SizeToContent = SizeToContent.Height;
        WindowStartupLocation = WindowStartupLocation.CenterOwner;
        ResizeMode = ResizeMode.NoResize;

        var root = new StackPanel { Margin = new Thickness(22, 20, 22, 18) };

        root.Children.Add(new TextBlock
        {
            Text = $"已更新到 {version}",
            FontSize = 18,
            FontWeight = FontWeights.Bold,
            Foreground = ChromePalette.BrushOf(ChromePalette.Ink, "#1B2836"),
            Margin = new Thickness(0, 0, 0, 4)
        });

        root.Children.Add(new TextBlock
        {
            Text = "下面几处跟以前不一样。不需要做任何操作也能正常上课；要改设置时再看第 1 条。这个提示只会出现一次。",
            FontSize = 12.5,
            Foreground = ChromePalette.BrushOf(ChromePalette.Muted, "#667085"),
            TextWrapping = TextWrapping.Wrap,
            Margin = new Thickness(0, 0, 0, 14)
        });

        foreach (var (title, detail) in items)
        {
            var block = new StackPanel { Margin = new Thickness(0, 0, 0, 11) };

            block.Children.Add(new TextBlock
            {
                Text = "· " + title,
                FontSize = 14,
                FontWeight = FontWeights.Bold,
                Foreground = ChromePalette.BrushOf(ChromePalette.Primary, "#1E4FA3"),
                TextWrapping = TextWrapping.Wrap
            });

            block.Children.Add(new TextBlock
            {
                Text = detail,
                FontSize = 13,
                Foreground = new SolidColorBrush(MediaColor.FromRgb(0x37, 0x41, 0x51)),
                TextWrapping = TextWrapping.Wrap,
                Margin = new Thickness(14, 2, 0, 0)
            });

            root.Children.Add(block);
        }

        var ok = new Button
        {
            Content = "知道了",
            FontSize = 14,
            FontWeight = FontWeights.Bold,
            Padding = new Thickness(26, 8, 26, 8),
            HorizontalAlignment = HAlign.Right,
            Margin = new Thickness(0, 8, 0, 0),
            Background = ChromePalette.BrushOf(ChromePalette.PrimaryLight, "#E9EFF9"),
            BorderBrush = ChromePalette.BrushOf(ChromePalette.PrimaryBorder, "#C2D2E9")
        };
        ok.Click += (_, _) => { DialogResult = true; };

        // r78：跳版升级（如 1.0.9 直接升到 1.0.13）会把中间每个版本的说明都带上，
        // 十几段叠下来窗口会撑到屏幕外，底部「知道了」根本点不到 —— 视觉上像程序卡死。
        // 现在：内容区封顶（工作区 82%）且可滚动，「知道了」固定在底部，不必滚到底才能关。
        var body = new ScrollViewer
        {
            VerticalScrollBarVisibility = ScrollBarVisibility.Auto,
            HorizontalScrollBarVisibility = ScrollBarVisibility.Disabled,
            Content = root
        };

        DockPanel.SetDock(ok, Dock.Bottom);
        ok.Margin = new Thickness(0, 12, 22, 14);

        // 按钮条与滚动内容之间压一条细线：否则最后一段说明和「知道了」糊在一起，
        // 看上去像按钮也是说明的一部分。
        var divider = new Border
        {
            Height = 1,
            Background = ChromePalette.BrushOf(ChromePalette.Line, "#E4E9F0"),
            Margin = new Thickness(22, 0, 22, 0)
        };
        DockPanel.SetDock(divider, Dock.Bottom);

        var shell = new DockPanel
        {
            LastChildFill = true,
            MaxHeight = Math.Max(360, SystemParameters.WorkArea.Height * 0.82)
        };
        shell.Children.Add(ok);
        shell.Children.Add(divider);
        shell.Children.Add(body);
        Content = shell;

        GlassChrome.Prepare(this);}

